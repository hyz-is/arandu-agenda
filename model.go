// Booking is one place taken on the team's agenda by a customer of a tenant.
//
// It embeds the model, so a row returned by a query carries the connection and
// can be saved again. Build a new row with Bookings(db).New(): a struct literal
// has no connection and its write methods return model.ErrUnwired.
//
// Bookings, BookingQuery and BookingCollection are generated beside this file,
// in BookingQuery.go, by aru model:build.
type Booking struct {
	model.Model

	// ID is the identifier, generated by the application.
	ID string `db:"id"`

	// TenantID is the space the booking belongs to. It is written from the Grant
	// and read back so the policy can compare it against the subject's tenant.
	TenantID string `db:"tenant_id"`

	// Code is the protocol number people say: "AG-000123". It is taken from the
	// counter, which every space shares, so it names one booking.
	Code string `db:"code"`

	// ServiceKey and ServiceName are the service as it was when the booking was
	// made. The name is a copy: renaming a service does not rewrite what a
	// customer booked.
	ServiceKey  string `db:"service_key"`
	ServiceName string `db:"service_name"`

	// SubjectType, SubjectID and SubjectLabel are what the booking is about,
	// opaque to this package: the application passes "camera", its own
	// identifier and a name for the screens.
	SubjectType  string `db:"subject_type"`
	SubjectID    string `db:"subject_id"`
	SubjectLabel string `db:"subject_label"`

	// RequesterID is the user of the tenant who booked. The application owns
	// what a user is; this package only compares the identifier with the
	// subject's. RequesterName is who they were when they booked, as the
	// Directory answered.
	RequesterID   string `db:"requester_id"`
	RequesterName string `db:"requester_name"`

	// CustomerNote is the line the customer left for the team.
	CustomerNote string `db:"customer_note"`

	// StartsAt and EndsAt are the slot the booking holds, in UTC.
	StartsAt time.Time `db:"starts_at"`
	EndsAt   time.Time `db:"ends_at"`

	// Status is where the booking stands.
	Status Status `db:"status"`

	// HoldUntil is when a booking that waits for payment gives its slot up. It
	// is nil once the booking holds its slot for good.
	HoldUntil *time.Time `db:"hold_until"`

	// PaymentRef is the application's reference of the payment that settled the
	// booking. Empty while nothing did.
	PaymentRef string `db:"payment_ref"`

	// ReleasedBy and ReleasedReason say who let the booking through without a
	// payment, and why.
	ReleasedBy     string `db:"released_by"`
	ReleasedReason string `db:"released_reason"`

	// ConfirmedAt is when the customer confirmed, RemindedAt when the reminder
	// went, CompletedAt when the team did the work. All in UTC.
	ConfirmedAt *time.Time `db:"confirmed_at"`
	RemindedAt  *time.Time `db:"reminded_at"`
	CompletedAt *time.Time `db:"completed_at"`

	// CompletedBy is the team member who marked it done, and TeamNote what they
	// wrote. The customer reads neither.
	CompletedBy string `db:"completed_by"`
	TeamNote    string `db:"team_note"`

	// Reschedules counts how many times the booking was moved.
	Reschedules int `db:"reschedules"`

	// CancelReason and CancelledBy say why a booking was cancelled and which
	// side did it.
	CancelReason string `db:"cancel_reason"`
	CancelledBy  string `db:"cancelled_by"`

	// CreatedAt is when the row was written, in UTC, and UpdatedAt when it last
	// changed.
	CreatedAt time.Time `db:"created_at"`
	UpdatedAt time.Time `db:"updated_at"`
}

