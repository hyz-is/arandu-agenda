// fieldsResource is a response made of named fields.
type fieldsResource map[string]any

// ToArray returns the fields.
func (f fieldsResource) ToArray() map[string]any { return f }

// With returns what goes beside the fields: nothing.
func (fieldsResource) With() map[string]any { return nil }

func instant(t time.Time) string { return t.UTC().Format(time.RFC3339) }

func optionalInstant(t *time.Time) any {
	if t == nil {
		return nil
	}
	return instant(*t)
}

// customerFields are the fields a booking answers the customer with. What the
// team wrote about it -- its note, who released it and why -- is not among
// them, because it is how the team works and not what the customer booked.
func customerFields(s Summary) map[string]any {
	return map[string]any{
		"id":            s.ID,
		"code":          s.Code,
		"service":       s.ServiceKey,
		"service_name":  s.ServiceName,
		"subject":       map[string]any{"type": s.Subject.Type, "id": s.Subject.ID, "label": s.Subject.Label},
		"requester_id":  s.RequesterID,
		"note":          s.CustomerNote,
		"starts_at":     instant(s.StartsAt),
		"ends_at":       instant(s.EndsAt),
		"status":        string(s.Status),
		"hold_until":    optionalInstant(s.HoldUntil),
		"confirmed_at":  optionalInstant(s.ConfirmedAt),
		"reschedules":   s.Reschedules,
		"cancel_reason": s.CancelReason,
		"created_at":    instant(s.CreatedAt),
		"updated_at":    instant(s.UpdatedAt),
	}
}

// teamFields are the fields a booking answers the team with: the space too,
// because the team reads every space's bookings and the code alone does not say
// whose, and what the team wrote.
func teamFields(s Summary) map[string]any {
	out := customerFields(s)
	out["tenant"] = s.Tenant
	out["requester_name"] = s.RequesterName
	out["payment_ref"] = s.PaymentRef
	out["released_by"] = s.ReleasedBy
	out["released_reason"] = s.ReleasedReason
	out["completed_by"] = s.CompletedBy
	out["completed_at"] = optionalInstant(s.CompletedAt)
	out["team_note"] = s.TeamNote
	out["cancelled_by"] = s.CancelledBy
	out["reminded_at"] = optionalInstant(s.RemindedAt)
	return out
}

func serviceFields(s ServiceView) map[string]any {
	return map[string]any{
		"id": s.ID, "key": s.Key, "name": s.Name, "description": s.Description, "duration_minutes": s.DurationMinutes,
		"requires_payment": s.RequiresPayment, "active": s.Active,
	}
}

