// protocol writes a booking number the way it is said and printed.
func protocol(number int64) string { return fmt.Sprintf("AG-%06d", number) }

// Occupies reports whether the booking holds its slot at that moment: it is
// scheduled or confirmed, or it waits for a payment inside its hold.
func (b Booking) Occupies(now time.Time) bool { return holds(b.Status, b.HoldUntil, now) }

// holds is Occupies for the columns a statement that crosses tenants reads.
func holds(status Status, holdUntil *time.Time, now time.Time) bool {
	switch status {
	case StatusScheduled, StatusConfirmed:
		return true
	case StatusAwaitingPayment:
		return holdUntil != nil && holdUntil.After(now)
	}
	return false
}

// Lapsed reports whether the booking waited for a payment and its hold is over,
// whether or not ExpireHolds already said so.
func (b Booking) Lapsed(now time.Time) bool {
	switch b.Status {
	case StatusExpired:
		return true
	case StatusAwaitingPayment:
		return b.HoldUntil == nil || !b.HoldUntil.After(now)
	}
	return false
}

// CanSettle reports whether a payment can be put on the booking: it waits for
// one, or its hold lapsed.
func (b Booking) CanSettle() bool {
	return b.Status == StatusAwaitingPayment || b.Status == StatusExpired
}

// CanMove reports whether the booking can be moved to another time: it still
// has a place to give up.
func (b Booking) CanMove() bool {
	return b.Status == StatusAwaitingPayment || b.Status == StatusScheduled || b.Status == StatusConfirmed
}

// ChangeOpen reports whether a customer can still move or cancel the booking:
// it can be moved, and the start is further away than until.
func (b Booking) ChangeOpen(now time.Time, until time.Duration) bool {
	return b.CanMove() && !now.Add(until).After(b.StartsAt)
}

// CanConfirm reports whether the customer can confirm the booking: it holds its
// slot for good, it was not confirmed yet, and it has not started.
func (b Booking) CanConfirm(now time.Time) bool {
	return b.Status == StatusScheduled && now.Before(b.StartsAt)
}

// CanComplete reports whether the team can mark the booking as done.
func (b Booking) CanComplete() bool {
	return b.Status == StatusScheduled || b.Status == StatusConfirmed
}

// CanNoShow reports whether the customer can be marked as absent: the booking
// held its slot and its start has passed.
func (b Booking) CanNoShow(now time.Time) bool {
	return b.CanComplete() && !now.Before(b.StartsAt)
}

// Confirm records that the customer will come.
func (b *Booking) Confirm(now time.Time) error {
	if !b.CanConfirm(now) {
		return fmt.Errorf("agenda: %s is %s and cannot be confirmed", b.Code, b.Status)
	}
	now = now.UTC()
	b.Status = StatusConfirmed
	b.ConfirmedAt = &now
	b.UpdatedAt = now
	return nil
}

// Settle puts the application's payment on the booking: the slot is held for
// good and the hold is over.
func (b *Booking) Settle(ref string, now time.Time) error {
	if !b.CanSettle() {
		return fmt.Errorf("agenda: %s is %s and takes no payment", b.Code, b.Status)
	}
	b.activate(now)
	b.PaymentRef = ref
	return nil
}

// Release lets the booking through without a payment, and keeps who did it and
// why.
func (b *Booking) Release(by, reason string, now time.Time) error {
	if !b.CanSettle() {
		return fmt.Errorf("agenda: %s is %s and cannot be released", b.Code, b.Status)
	}
	b.activate(now)
	b.ReleasedBy = by
	b.ReleasedReason = reason
	return nil
}

// activate makes the booking hold its slot for good.
func (b *Booking) activate(now time.Time) {
	b.Status = StatusScheduled
	b.HoldUntil = nil
	b.UpdatedAt = now.UTC()
}

// Move gives the booking another time. The payment, the code and the hold stay;
// the confirmation and the reminder belong to the old time and go, so the new
// one is reminded and confirmed on its own.
func (b *Booking) Move(start, end, now time.Time) error {
	if !b.CanMove() {
		return fmt.Errorf("agenda: %s is %s and cannot be moved", b.Code, b.Status)
	}
	if !end.After(start) {
		return fmt.Errorf("agenda: %s cannot end before it starts", b.Code)
	}
	b.StartsAt, b.EndsAt = start.UTC(), end.UTC()
	if b.Status == StatusConfirmed {
		b.Status = StatusScheduled
	}
	b.ConfirmedAt, b.RemindedAt = nil, nil
	b.Reschedules++
	b.UpdatedAt = now.UTC()
	return nil
}

// Cancel gives the slot up. side is who did it: ByCustomer or ByTeam.
func (b *Booking) Cancel(side, reason string, now time.Time) error {
	if !b.CanMove() {
		return fmt.Errorf("agenda: %s is %s and cannot be cancelled", b.Code, b.Status)
	}
	b.Status = StatusCancelled
	b.HoldUntil = nil
	b.CancelledBy = side
	b.CancelReason = reason
	b.UpdatedAt = now.UTC()
	return nil
}

// Complete records that the team did the work.
func (b *Booking) Complete(by, note string, now time.Time) error {
	if !b.CanComplete() {
		return fmt.Errorf("agenda: %s is %s and cannot be completed", b.Code, b.Status)
	}
	now = now.UTC()
	b.Status = StatusCompleted
	b.CompletedAt = &now
	b.CompletedBy = by
	b.TeamNote = note
	b.UpdatedAt = now
	return nil
}

// MarkNoShow records that the customer did not turn up.
func (b *Booking) MarkNoShow(now time.Time) error {
	if !b.CanNoShow(now) {
		return fmt.Errorf("agenda: %s is %s and cannot be marked as absent before its start", b.Code, b.Status)
	}
	b.Status = StatusNoShow
	b.UpdatedAt = now.UTC()
	return nil
}

// Expire gives up the slot of a booking whose hold is over.
func (b *Booking) Expire(now time.Time) error {
	if b.Status != StatusAwaitingPayment || !b.Lapsed(now) {
		return fmt.Errorf("agenda: %s is %s and its hold is not over", b.Code, b.Status)
	}
	b.Status = StatusExpired
	b.UpdatedAt = now.UTC()
	return nil
}

