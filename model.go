// Status is where a booking stands.
type Status string

// The statuses of a booking.
const (
	// StatusAwaitingPayment is a booking that holds its slot until HoldUntil and
	// waits for the application to say the payment settled.
	StatusAwaitingPayment Status = "awaiting_payment"
	// StatusScheduled is a booking that holds its slot: paid, released as a
	// courtesy, or made for a service that asks for no payment.
	StatusScheduled Status = "scheduled"
	// StatusConfirmed is a scheduled booking the customer confirmed.
	StatusConfirmed Status = "confirmed"
	// StatusCompleted is a booking the team did.
	StatusCompleted Status = "completed"
	// StatusCancelled is a booking nobody will show up to, cancelled by the
	// customer or by the team.
	StatusCancelled Status = "cancelled"
	// StatusExpired is a booking whose hold lapsed before a payment came.
	StatusExpired Status = "expired"
	// StatusNoShow is a booking the customer did not turn up for.
	StatusNoShow Status = "no_show"
)

// Statuses are every status, in the order the screens list them.
var Statuses = []Status{
	StatusAwaitingPayment, StatusScheduled, StatusConfirmed, StatusCompleted, StatusCancelled, StatusExpired, StatusNoShow,
}

// Valid reports whether the status is one of the seven.
func (s Status) Valid() bool {
	for _, known := range Statuses {
		if s == known {
			return true
		}
	}
	return false
}

// Flag is a yes-or-no a column holds as an integer, read back from whatever an
// engine answers with: the engines disagree about booleans and one place has
// to flatten them.
type Flag bool

// Value writes the flag as the integer the column holds.
func (f Flag) Value() (driver.Value, error) {
	if f {
		return int64(1), nil
	}
	return int64(0), nil
}

// Scan reads the flag back. Anything it cannot read is refused rather than
// read as false.
func (f *Flag) Scan(value any) error {
	switch v := value.(type) {
	case nil:
		*f = false
	case bool:
		*f = Flag(v)
	case int64:
		*f = v != 0
	case int32:
		*f = v != 0
	case int:
		*f = v != 0
	case float64:
		*f = v != 0
	case []byte:
		return f.Scan(string(v))
	case string:
		b, err := strconv.ParseBool(v)
		if err != nil {
			return fmt.Errorf("agenda: %q is not a yes-or-no", v)
		}
		*f = Flag(b)
	default:
		return fmt.Errorf("agenda: cannot read %T as a yes-or-no", value)
	}
	return nil
}

// Service is something the team does for a customer at a time: a camera
// reconfiguration, an installation. The team's catalogue of them is shared by
// every space, so the table has no tenant column: it is Global, written only by
// the team's service after the team's policy answered, and read by a customer
// only to book.
//
// It carries no price. What a service costs is the application's catalogue, and
// RequiresPayment only says the booking waits for the application's word that
// it was paid.
//
// Services, ServiceQuery and ServiceCollection are generated beside this file,
// in ServiceQuery.go, by aru model:build.
type Service struct {
	model.Model

	// ID is the identifier, generated by the application.
	ID string `db:"id"`

	// Key is the stable name the application and a booking refer to it by:
	// "instalacao", "reconfiguracao". It is unique.
	Key string `db:"key"`

	// Name and Description are what the screens show.
	Name        string `db:"name"`
	Description string `db:"description"`

	// DurationMinutes is how long the team takes, and so how long a booking
	// holds its slot.
	DurationMinutes int `db:"duration_minutes"`

	// RequiresPayment says a booking of this service waits for a payment.
	RequiresPayment Flag `db:"requires_payment"`

	// Active says the service is offered. An inactive one keeps the bookings
	// already made and takes no new one.
	Active Flag `db:"active"`

	// CreatedAt and UpdatedAt are when the row was written and last changed, in
	// UTC.
	CreatedAt time.Time `db:"created_at"`
	UpdatedAt time.Time `db:"updated_at"`
}

